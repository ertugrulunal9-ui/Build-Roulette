/**
 * Bundles the `import-url` Edge Function's code (src/import-url/entry.ts: the handler and the
 * copier) into one ES module for Deno: supabase/functions/import-url/core.js. Platform-neutral:
 * a Node built-in in the graph fails the build. Paths in the output are relative to this
 * package, so the output is the same on every machine (function-bundle.test.ts compares it
 * with the committed file). Same pattern as the `jobs` function
 * (apps/capture-worker/scripts/function-bundle.ts).
 */
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

export const PACKAGE_DIR = fileURLToPath(new URL('../', import.meta.url));
export const FUNCTION_BUNDLE = fileURLToPath(
  new URL('../../../supabase/functions/import-url/core.js', import.meta.url),
);

const BANNER = `// GENERATED by \`pnpm --filter @br/site build:function\` from
// packages/site/src/import-url/entry.ts (T-051). Do not edit; change the sources and rebuild.
// A unit test (packages/site/scripts/function-bundle.test.ts) fails when this is stale.`;

export async function bundleFunction(): Promise<string> {
  const result = await build({
    absWorkingDir: PACKAGE_DIR,
    entryPoints: ['src/import-url/entry.ts'],
    bundle: true,
    format: 'esm',
    platform: 'neutral',
    target: 'es2022',
    mainFields: ['module', 'main'],
    resolveExtensions: ['.ts', '.js', '.mjs'],
    write: false,
    metafile: true,
    charset: 'utf8',
    legalComments: 'none',
    banner: { js: BANNER },
    logLevel: 'silent',
  });
  const node = Object.keys(result.metafile.inputs).filter((p) => p.startsWith('node:'));
  if (node.length > 0) throw new Error(`Node built-ins in the function bundle: ${node.join(', ')}`);
  const out = result.outputFiles[0];
  if (!out) throw new Error('esbuild produced no output');
  return out.text;
}
